    private void btnIniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarActionPerformed
        
        // leer los nombres escritos en los campos de texto
        String caballo1 = txtCaballo1.getText();
        String caballo2 = txtCaballo2.getText();
        String caballo3 = txtCaballo3.getText();
        
        // Poner las barras a 0 por si se repite la carrera
        barra1.setValue(0);
        barra2.setValue(0);
        barra3.setValue(0);
        
        lblGanador.setText("Carrera en curso...");
        
        // Crear los caballos, cada uno con su nombre y su barra
        CaballoEj3 c1 = new CaballoEj3(caballo1, barra1);
        CaballoEj3 c2 = new CaballoEj3(caballo2, barra2);
        CaballoEj3 c3 = new CaballoEj3(caballo3, barra3);
        
        // Crear un hilo para cada caballo
        Thread hilo1 = new Thread(c1);
        Thread hilo2 = new Thread(c2);
        Thread hilo3 = new Thread(c3);
        
        // Dar la salida a los tres hilos a la vez
        hilo1.start();
        hilo2.start();
        hilo3.start();
        
      // Hilo "juez": espera a que lleguen los tres y anuncia el ganador
      new Thread(() -> {
         try {
             // El juez espera en la meta a los tres caballos
             hilo1.join();
             hilo2.join();
             hilo3.join();
             
             // Comparar tiempos 
             String ganador;
             if (c1.getTiempo() <= c2.getTiempo() && c1.getTiempo() <= c3.getTiempo()) {
                 ganador = c1.getNombreCaballo();
             } else if (c2.getTiempo() <= c1.getTiempo() && c2.getTiempo() <= c3.getTiempo()) {
                 ganador = c2.getNombreCaballo();
             } else {
                 ganador = c3.getNombreCaballo();
             }
             
             // Solo el hilo de la interfaz puede escribir en la ventana
             SwingUtilities.invokeLater(() -> {
                 lblGanador.setText("El ganador es: "+ ganador);
             });
         } catch (InterruptedException e) {
             System.out.println("El juez ha sido interumpido.");
         }
      }).start();
        
    }//GEN-LAST:event_btnIniciarActionPerformed

